-- =====================================================================
-- TICKET DATABASE  (owner: ticket-service)
-- =====================================================================

CREATE TABLE tickets (
    ticket_id        BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- shown as SD-<id>
    title            VARCHAR(200) NOT NULL,
    description      TEXT         NOT NULL,
    created_by       UUID         NOT NULL,                       -- users.user_id (auth DB, logical link); name/email looked up there
    department_name  VARCHAR(20)  NOT NULL,                       -- which department pool it sits in
    status           VARCHAR(30)  NOT NULL DEFAULT 'OPEN',
    issue_key        VARCHAR(60),                                 -- AI label, e.g. 'wifi-outage'
    idempotency_key  VARCHAR(100),
    created_at       TIMESTAMPTZ,
    updated_at       TIMESTAMPTZ,
    resolved_at      TIMESTAMPTZ,
    CONSTRAINT uk_tickets_idempotency UNIQUE (created_by, idempotency_key),
    CONSTRAINT ck_tickets_dept   CHECK (department_name IN ('IT', 'HR', 'OPERATIONS', 'UNCLASSIFIED')),
    CONSTRAINT ck_tickets_status CHECK (status IN ('OPEN', 'IN_PROGRESS', 'WAITING_ON_EMPLOYEE', 'RESOLVED', 'CLOSED'))
);
CREATE INDEX idx_tickets_dept_status_created ON tickets (department_name, status, created_at);  -- department pool
CREATE INDEX idx_tickets_creator_created     ON tickets (created_by, created_at);               -- my tickets
CREATE INDEX idx_tickets_dept_created        ON tickets (department_name, created_at);          -- today's inflow (daily limit)
CREATE INDEX idx_tickets_incident            ON tickets (department_name, issue_key, created_at); -- incidents: same dept + issue_key within 4h

-- AI triage result: exactly ONE per ticket (1:1)
CREATE TABLE ai_analysis_results (
    result_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     BIGINT       NOT NULL REFERENCES tickets (ticket_id) ON DELETE CASCADE,
    category      VARCHAR(20)  NOT NULL,
    priority      VARCHAR(20)  NOT NULL,
    ai_summary    VARCHAR(500),
    source        VARCHAR(20)  NOT NULL,                          -- AI / FALLBACK / MANUAL override
    completed_at  TIMESTAMPTZ,
    CONSTRAINT uk_analysis_ticket   UNIQUE (ticket_id),
    CONSTRAINT ck_analysis_category CHECK (category IN ('IT', 'HR', 'OPERATIONS', 'UNCLASSIFIED')),
    CONSTRAINT ck_analysis_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_analysis_source   CHECK (source IN ('AI', 'FALLBACK', 'MANUAL'))
);
CREATE INDEX idx_analysis_category ON ai_analysis_results (category);

-- Who is working on the ticket: exactly ONE per ticket (1:1)
CREATE TABLE ticket_assignments (
    assignment_id  BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id      BIGINT       NOT NULL REFERENCES tickets (ticket_id) ON DELETE CASCADE,
    agent_id       UUID         NOT NULL,                         -- the agent (auth DB, logical link)
    assigned_at    TIMESTAMPTZ,
    completed_at   TIMESTAMPTZ,                                   -- set when the employee confirms
    CONSTRAINT uk_assignment_ticket UNIQUE (ticket_id)            -- a ticket can't be claimed twice
);
CREATE INDEX idx_assignments_agent_day ON ticket_assignments (agent_id, assigned_at);   -- tickets taken today (daily limit)
